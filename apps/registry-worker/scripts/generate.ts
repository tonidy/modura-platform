/**
 * Writes src/generated/: the contract facts the Worker serves, taken from the same
 * sources the Go service uses, so neither can drift from the contract silently.
 *
 * - ir-checks.js: ir.schema.json compiled ahead of time. Workers forbid code
 *   generation from strings, so Ajv cannot compile it at request time.
 * - api-checks.js: each operation's input schema from generated/openapi/registry-go.json.
 * - contract.json: the operations (kind, permissions) and the error catalog with
 *   HTTP statuses, from the OpenAPI document and the IR.
 *
 * With --check, fails if a file on disk differs from what would be written.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Ajv } from 'ajv';
import { Ajv2020 } from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { irJsonSchemas } from '@modura/compiler';
import { httpStatusFor, type ErrorCategory } from '@modura/runtime-contracts';

const root = join(import.meta.dirname, '../../..');
const out = join(import.meta.dirname, '../src/generated');
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

interface Operation {
  'x-modura-operation': string;
  'x-modura-kind': string;
  'x-modura-requires': string[];
  'x-modura-idempotent'?: boolean;
  requestBody: { content: { 'application/json': { schema: { $ref: string } } } };
}

const spec = readJson('generated/openapi/registry-go.json') as {
  paths: Record<string, { post?: Operation }>;
  components: object;
};
const ir = readJson('generated/ir/modura.ir.json') as {
  platformErrors: Record<string, { category: ErrorCategory; retryable: boolean }>;
  modules: Record<string, { errors: Record<string, { category: ErrorCategory; retryable: boolean }> }>;
};

const irAjv = new Ajv2020({ allErrors: false, strict: false, code: { source: true, esm: true } });
const schemas = irJsonSchemas();
irAjv.addSchema(schemas.strict, 'strict');
irAjv.addSchema({ ...schemas.lenient, $id: 'urn:modura:ir:1.0:lenient' }, 'lenient');

const apiAjv = new Ajv({ allErrors: false, strict: false, code: { source: true, esm: true } });
apiAjv.addFormat('uuid', UUID);
apiAjv.addFormat('int64', true);
apiAjv.addSchema({ $id: 'urn:modura:openapi', components: spec.components });

const operations: Record<string, object> = {};
const inputChecks: Record<string, string> = {};
for (const [path, item] of Object.entries(spec.paths).sort(([a], [b]) => a.localeCompare(b))) {
  const op = item.post;
  if (!op) continue;
  const check = `input${Object.keys(operations).length}`;
  apiAjv.addSchema({ $ref: `urn:modura:openapi${op.requestBody.content['application/json'].schema.$ref}` }, check);
  inputChecks[check] = check;
  operations[path] = {
    id: op['x-modura-operation'],
    kind: op['x-modura-kind'],
    requires: op['x-modura-requires'],
    idempotent: op['x-modura-idempotent'] === true,
    check,
  };
}

const errors: Record<string, object> = {};
const define = (code: string, def: { category: ErrorCategory; retryable: boolean }) => {
  errors[code] = { category: def.category, retryable: def.retryable, status: httpStatusFor(def.category) };
};
for (const [code, def] of Object.entries(ir.platformErrors)) define(code, def);
for (const [module, definition] of Object.entries(ir.modules)) {
  for (const [code, def] of Object.entries(definition.errors)) define(`${module}.${code}`, def);
}

const header = '// Generated by apps/registry-worker/scripts/generate.ts. Do not edit.\n';
const checkTypes = (names: string[]) =>
  `${header}import type { SchemaCheck } from '@modura/compiler';\n${names.map((n) => `export declare const ${n}: SchemaCheck;\n`).join('')}`;

const files: Record<string, string> = {
  'ir-checks.js': header + standaloneCode(irAjv, { strict: 'strict', lenient: 'lenient' }),
  'ir-checks.d.ts': checkTypes(['strict', 'lenient']),
  'api-checks.js': header + standaloneCode(apiAjv, inputChecks),
  'api-checks.d.ts': checkTypes(Object.keys(inputChecks)),
  'contract.json': `${JSON.stringify({ operations, errors }, null, 2)}\n`,
};

const check = process.argv.includes('--check');
let stale = false;
for (const [name, text] of Object.entries(files)) {
  const file = join(out, name);
  if (!check) {
    writeFileSync(file, text);
    continue;
  }
  let current = '';
  try {
    current = readFileSync(file, 'utf8');
  } catch {}
  if (current !== text) {
    console.error(`apps/registry-worker/src/generated/${name} is stale.`);
    stale = true;
  }
}
if (stale) {
  console.error('Run `pnpm generate` and commit the result.');
  process.exit(1);
}
console.log(check ? 'Worker generated files are up to date.' : `Wrote ${Object.keys(files).length} files.`);

function readJson(path: string): unknown {
  return JSON.parse(readFileSync(join(root, path), 'utf8'));
}
