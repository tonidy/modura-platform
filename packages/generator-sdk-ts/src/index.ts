import {
  listOperations,
  pascalCase,
  type IrDocument,
  type IrObjectType,
  type IrType,
} from '@modura/compiler';

export interface SdkOptions {
  /**
   * Module name to the service that implements it (plan M7). Each call then names
   * its service, and the transport picks that service's base URL.
   */
  readonly services?: Readonly<Record<string, string>>;
}

/**
 * Generates the typed half of the TypeScript SDK: one type per IR type, one error-code
 * union per operation, and a client factory. Transport lives in the handwritten
 * runtime, the `@modura/sdk` package, which the generated file imports.
 */
export function generateSdk(ir: IrDocument, sdkOptions: SdkOptions = {}): string {
  const out: string[] = [
    `// Generated by \`pnpm generate\` from IR ${ir.irVersion}. Do not edit.`,
    '',
    "import type { CallOptions, IdempotentCallOptions, JsonValue, Money, Result, Transport } from '@modura/sdk';",
    '',
  ];

  for (const [name, type] of Object.entries(ir.types)) {
    out.push(...declaration(pascalCase(name), type), '');
  }

  const operations = listOperations(ir);
  for (const { id, module, name, operation } of operations) {
    const base = pascalCase(module, name);
    out.push(`// ${id}`, '');
    out.push(...declaration(`${base}Input`, operation.input), '');
    if (operation.output.kind !== 'ref') {
      out.push(...declaration(`${base}Output`, operation.output), '');
    }
    out.push(`export type ${base}ErrorCode =`);
    out.push(...operation.errors.map((code, i, all) => `  | ${JSON.stringify(code)}${i === all.length - 1 ? ';' : ''}`));
    out.push('');
  }

  for (const [module, definition] of Object.entries(ir.modules)) {
    for (const [name, event] of Object.entries(definition.events)) {
      out.push(`// event ${module}.${name}`, '');
      out.push(...docComment(event.description, ''));
      out.push(...declaration(`${pascalCase(module, name)}Event`, event.payload), '');
    }
  }

  out.push('export function createModuraClient(transport: Transport) {', '  return {');
  for (const module of Object.keys(ir.modules)) {
    out.push(`    ${module}: {`);
    for (const { id, name, operation } of operations.filter((entry) => entry.module === module)) {
      const base = pascalCase(module, name);
      const output = operation.output.kind === 'ref' ? typeExpression(operation.output) : `${base}Output`;
      const options = operation.idempotent
        ? 'options: IdempotentCallOptions'
        : 'options?: CallOptions';
      const service = sdkOptions.services?.[module];
      const callOptions = service ? `{ ...options, service: ${JSON.stringify(service)} }` : 'options';
      out.push(
        ...docComment(operation.description, '      '),
        `      ${name}: (input: ${base}Input, ${options}): Promise<Result<${output}, ${base}ErrorCode>> =>`,
        `        transport.call(${JSON.stringify(id)}, input, ${callOptions}),`,
      );
    }
    out.push('    },');
  }
  out.push('  };', '}', '', 'export type ModuraClient = ReturnType<typeof createModuraClient>;', '');

  return out.join('\n');
}

function declaration(name: string, type: IrType): string[] {
  const doc = 'description' in type && type.description ? docComment(type.description, '') : [];
  if (type.kind !== 'object') return [...doc, `export type ${name} = ${typeExpression(type)};`];
  if (Object.keys(type.fields).length === 0) {
    return [...doc, `export type ${name} = Record<string, never>;`];
  }
  return [...doc, `export interface ${name} {`, ...fieldLines(type, '  '), '}'];
}

function fieldLines(type: IrObjectType, indent: string): string[] {
  return Object.entries(type.fields).flatMap(([name, field]) => {
    const doc =
      'description' in field.type && field.type.description
        ? docComment(field.type.description, indent)
        : [];
    const optional = field.required ? '' : '?';
    return [...doc, `${indent}${name}${optional}: ${typeExpression(field.type)};`];
  });
}

function typeExpression(type: IrType): string {
  switch (type.kind) {
    case 'string':
    case 'timestamp':
      return 'string';
    case 'integer':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'money':
      return 'Money';
    case 'json':
      return 'JsonValue';
    case 'enum':
      return type.values.map((value) => JSON.stringify(value)).join(' | ');
    case 'array':
      return `Array<${typeExpression(type.items)}>`;
    case 'object': {
      const fields = Object.entries(type.fields).map(
        ([name, field]) => `${name}${field.required ? '' : '?'}: ${typeExpression(field.type)}`,
      );
      return fields.length === 0 ? 'Record<string, never>' : `{ ${fields.join('; ')} }`;
    }
    case 'ref':
      return pascalCase(type.name);
  }
}

function docComment(text: string, indent: string): string[] {
  return [`${indent}/** ${text.replaceAll('*/', '*\\/')} */`];
}
